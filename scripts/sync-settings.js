#!/usr/bin/env node

/**
 * Sync Settings Schema
 *
 * Reads the single source of truth (settings-schema.json) and generates:
 *   1. src/config/settings.generated.ts – SettingKey / SettingTypes /
 *      DEFAULT_SETTINGS / DEFAULT_RENDER_SETTINGS / normalizeSetting()
 *   2. mobile/lib/config/settings_defaults.g.dart – Dart default constants
 *
 * Run:  node scripts/sync-settings.js
 * Also invoked automatically at the start of every platform build.
 *
 * NEVER hardcode a setting default anywhere else — edit settings-schema.json
 * and re-run this script. See plans/config-centralization-plan.md.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, '..');

// ---------------------------------------------------------------------------
// Read source config
// ---------------------------------------------------------------------------
const schema = JSON.parse(
  fs.readFileSync(path.join(projectRoot, 'settings-schema.json'), 'utf8')
);

/** Settings exposed through the shared ISettingsService (excludes cliOnly). */
const settings = schema.settings.filter(s => !s.cliOnly);
/** Settings used by the documd CLI (render flag + cliOnly, renderKey remapped). */
const renderSettings = schema.settings.filter(
  s => s.cliOnly || s.render
);

let changed = false;

// ---------------------------------------------------------------------------
// Helper: write file only if content actually changed
// ---------------------------------------------------------------------------
function writeIfChanged(filePath, content) {
  const existing = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : '';
  if (existing !== content) {
    fs.writeFileSync(filePath, content, 'utf8');
    console.log(`  • Updated ${path.relative(projectRoot, filePath)}`);
    changed = true;
  }
}

// ---------------------------------------------------------------------------
// TS helpers
// ---------------------------------------------------------------------------

/** TS type for a setting: enum union, or scalar type. */
function tsScalarType(s) {
  if (s.type === 'enum') {
    return s.values.map(v => `'${v}'`).join(' | ');
  }
  if (s.type === 'boolean') return 'boolean';
  if (s.type === 'number') return 'number';
  return 'string';
}

function tsDefaultLiteral(s) {
  if (typeof s.default === 'string') return `'${s.default}'`;
  return String(s.default);
}

/** JS expression validating a raw value for a setting, else the default. */
function tsNormalizeExpr(s, rawVar) {
  const def = tsDefaultLiteral(s);
  if (s.type === 'enum') {
    const check = s.values.map(v => `${rawVar} === '${v}'`).join(' || ');
    return `(${check}) ? ${rawVar} : ${def}`;
  }
  if (s.type === 'boolean') {
    return `(typeof ${rawVar} === 'boolean') ? ${rawVar} : ${def}`;
  }
  if (s.type === 'number') {
    const bounds = [];
    if (typeof s.min === 'number') bounds.push(`${rawVar} >= ${s.min}`);
    if (typeof s.max === 'number') bounds.push(`${rawVar} <= ${s.max}`);
    const boundsStr = bounds.length ? ` && ${bounds.join(' && ')}` : '';
    return `(typeof ${rawVar} === 'number'${boundsStr}) ? ${rawVar} : ${def}`;
  }
  // string
  return `(typeof ${rawVar} === 'string') ? ${rawVar} : ${def}`;
}

// ---------------------------------------------------------------------------
// 1. Generate src/config/settings.generated.ts
// ---------------------------------------------------------------------------
function generateSettingsTs() {
  const lines = [];
  lines.push(
    '// AUTO-GENERATED by scripts/sync-settings.js — DO NOT EDIT',
    '// Source of truth: settings-schema.json',
    '//',
    '// To change a default/type/validation: edit settings-schema.json and run',
    '// `node scripts/sync-settings.js`. See plans/config-centralization-plan.md.',
    '',
  );

  // SettingKey
  lines.push('/** All available setting keys (excludes CLI-only entries). */');
  lines.push('export type SettingKey =');
  settings.forEach((s, i) => {
    // Each entry is a separate line with a leading `|`; only the last gets `;`
    lines.push(`  | '${s.key}'${i === settings.length - 1 ? ';' : ''}`);
  });
  lines.push('');
  // SettingTypes
  lines.push('/** Setting value types mapped by key. */');
  lines.push('export interface SettingTypes {');
  for (const s of settings) {
    const doc = s.doc ? `  /** ${s.doc} */` : null;
    if (doc) lines.push(doc);
    lines.push(`  ${s.key}: ${tsScalarType(s)};`);
  }
  lines.push('}');
  lines.push('');

  // DEFAULT_SETTINGS
  lines.push('/** Default values for all shared settings. */');
  lines.push('export const DEFAULT_SETTINGS: SettingTypes = {');
  for (const s of settings) {
    lines.push(`  ${s.key}: ${tsDefaultLiteral(s)},`);
  }
  lines.push('};');
  lines.push('');

  // DEFAULT_RENDER_SETTINGS (CLI / render pipeline)
  lines.push('/**');
  lines.push(' * Default render/layout settings for the documd CLI and render pipeline.');
  lines.push(' * `theme`/`language` are deliberately separate from the extension settings');
  lines.push(' * (`themeId`/`preferredLocale`): one is the rendered document, the other the UI.');
  lines.push(' */');
  lines.push('export const DEFAULT_RENDER_SETTINGS = {');
  for (const s of renderSettings) {
    const key = s.renderKey || s.key;
    lines.push(`  /** ${s.doc || key} */`);
    lines.push(`  ${key}: ${tsDefaultLiteral(s)},`);
  }
  lines.push('} as const;');
  lines.push('');

  // normalizeSetting
  lines.push('/**');
  lines.push(' * Normalize a raw (possibly invalid/absent) setting value against the schema.');
  lines.push(' * Returns the value if valid, otherwise the schema default.');
  lines.push(' * This is the SINGLE fallback entry point — platforms must not re-implement');
  lines.push(' * their own per-key fallback logic.');
  lines.push(' */');
  lines.push('export function normalizeSetting<K extends SettingKey>(');
  lines.push('  key: K,');
  lines.push('  raw: unknown,');
  lines.push('): SettingTypes[K];');
  // Implementation signature: switch can't narrow the generic K, so the
  // implementation returns `unknown` and the overload provides exact types.
  lines.push('export function normalizeSetting(');
  lines.push('  key: SettingKey,');
  lines.push('  raw: unknown,');
  lines.push('): unknown {');
  lines.push('  switch (key) {');
  for (const s of settings) {
    lines.push(`    case '${s.key}':`);
    lines.push(`      return ${tsNormalizeExpr(s, 'raw')};`);
  }
  lines.push('    default:');
  lines.push("      throw new Error(`Unknown setting key: ${String(key)}`);");
  lines.push('  }');
  lines.push('}');
  lines.push('');

  writeIfChanged(
    path.join(projectRoot, 'src/config/settings.generated.ts'),
    lines.join('\n'),
  );
}

// ---------------------------------------------------------------------------
// 2. Generate mobile/lib/config/settings_defaults.g.dart
// ---------------------------------------------------------------------------
function generateSettingsDart() {
  const lines = [];
  lines.push(
    '// AUTO-GENERATED by scripts/sync-settings.js — DO NOT EDIT',
    '// Source of truth: settings-schema.json',
    '//',
    '// To change a default: edit settings-schema.json and run',
    '// `node scripts/sync-settings.js`. See plans/config-centralization-plan.md.',
    '',
    "// Shared setting defaults for the mobile (Flutter) settings service.",
    "// Keys use the mobile storage names (dartKey) where they differ from the TS key.",
    '',
  );

  for (const s of settings) {
    // Every shared setting gets a Dart constant; mobile storage name comes
    // from dartKey when it differs from the TS key (e.g. docxHrDisplay → hrDisplay).
    const name = (s.dartKey || s.key).charAt(0).toUpperCase() + (s.dartKey || s.key).slice(1);
    const dartDefault = s.dartDefault !== undefined ? s.dartDefault : s.default;
    const literal = typeof dartDefault === 'string'
      ? `'${dartDefault}'`
      : String(dartDefault);
    lines.push(`const k${name}Default = ${literal};`);
  }

  writeIfChanged(
    path.join(projectRoot, 'mobile/lib/config/settings_defaults.g.dart'),
    lines.join('\n') + '\n',
  );
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------
export default function syncSettings() {
  console.log('⚙️  Syncing settings schema...');
  changed = false;

  generateSettingsTs();
  generateSettingsDart();

  if (!changed) {
    console.log('  ✓ No changes (generated files already up to date)');
  }
  return changed;
}

// Allow direct execution: node scripts/sync-settings.js
if (import.meta.url === `file://${process.argv[1]}`) {
  syncSettings();
}
