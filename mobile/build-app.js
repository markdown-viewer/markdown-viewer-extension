#!/usr/bin/env node

/**
 * Flutter App Build Script
 * 
 * Usage:
 *   node mobile/build-app.js <target>
 * 
 * Targets:
 *   ios            - Build iOS IPA for distribution
 *   ios:sim        - Build iOS app for simulator
 *   android        - Build Android release APK (and AAB when release signing is configured)
 *   macos          - Build macOS app (universal)
 *   macos:local    - Build macOS app for this machine's architecture only
 *   all            - Build every distribution target
 */

import { execSync } from 'child_process';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, '..');
const mobileDir = __dirname;
const distDir = path.join(projectRoot, 'dist');

/**
 * Check and fix Flutter platform configuration files
 * The ephemeral/Flutter-Generated.xcconfig is generated by flutter build
 */
function ensureFlutterConfig(platform) {
  const platformDir = path.join(mobileDir, platform);
  const flutterDir = path.join(platformDir, 'Flutter');
  const ephemeralDir = path.join(flutterDir, 'ephemeral');
  const generatedConfig = path.join(ephemeralDir, 'Flutter-Generated.xcconfig');
  
  // Check if Flutter-Generated.xcconfig exists
  // This file is generated during the first build, so we just need to ensure
  // flutter pub get has been run (which creates the ephemeral directory structure)
  if (!fs.existsSync(ephemeralDir)) {
    console.log(`  ⚠️  Missing ephemeral directory, running flutter pub get...`);
    execSync('flutter pub get', { cwd: mobileDir, stdio: 'inherit' });
    console.log(`  ✅ Flutter dependencies ready`);
  }
  
  // Flutter-Generated.xcconfig will be created during the build process
  // No need to check for it here
}

/**
 * Execute command with logging
 */
function exec(cmd, options = {}) {
  console.log(`  $ ${cmd}`);
  execSync(cmd, { stdio: 'inherit', ...options });
}

/**
 * Copy directory recursively using system cp command
 * This handles symlinks properly (required for macOS .app bundles)
 */
function copyDirectory(src, dest) {
  if (!fs.existsSync(src)) {
    throw new Error(`Source directory not found: ${src}`);
  }
  
  if (fs.existsSync(dest)) {
    fs.rmSync(dest, { recursive: true, force: true });
  }
  
  const destParent = path.dirname(dest);
  fs.mkdirSync(destParent, { recursive: true });
  
  // Use system cp -a to preserve symlinks (required for .app bundles)
  execSync(`cp -a "${src}" "${dest}"`, { stdio: 'inherit' });
}

/**
 * Copy files matching pattern
 */
function copyFiles(srcDir, destDir, pattern) {
  if (!fs.existsSync(srcDir)) {
    throw new Error(`Source directory not found: ${srcDir}`);
  }
  
  fs.mkdirSync(destDir, { recursive: true });
  
  const files = fs.readdirSync(srcDir);
  for (const file of files) {
    if (pattern.test(file)) {
      fs.copyFileSync(
        path.join(srcDir, file),
        path.join(destDir, file)
      );
      console.log(`  ✓ Copied ${file}`);
    }
  }
}

/**
 * Build targets
 */

/**
 * The architecture Xcode names for this machine (arm64 / x86_64).
 */
function hostXcodeArch() {
  return process.arch === 'x64' ? 'x86_64' : process.arch;
}

/**
 * macOS build, in two variants.
 *
 * `macos` is universal (x86_64 + arm64) — what a distribution build needs.
 * `macos:local` builds for the host architecture only, which is both faster and
 * the way around a toolchain bug: Flutter 3.38 hands the whole `ARCHS` list to a
 * single `lipo -verify_arch` call, while Xcode 27's lipo accepts exactly one
 * architecture per call, so a universal build fails at the framework check
 * ("does not contain architectures") *after* a successful compile. Flutter
 * forwards FLUTTER_XCODE_* to xcodebuild, which is how the list is narrowed.
 */
function buildMacos({ singleArch = false } = {}) {
  const arch = hostXcodeArch();
  const label = singleArch ? `${arch} only` : 'universal';
  console.log(`\n🖥️  Building macOS app (${label})...\n`);

  ensureFlutterConfig('macos');

  const options = { cwd: mobileDir };
  if (singleArch) {
    options.env = { ...process.env, FLUTTER_XCODE_ARCHS: arch };
  } else {
    console.log('  ℹ️  Universal build. If it fails with "does not contain architectures",');
    console.log('      that is the Flutter 3.38 + Xcode 27 lipo incompatibility, not this app;');
    console.log('      use `npm run build:macos:local` for a host-arch build.\n');
  }

  try {
    exec('flutter build macos', options);
  } catch (error) {
    if (!singleArch) {
      console.error('\n❌ Universal macOS build failed.');
      console.error('   If the log mentions "does not contain architectures", rebuild with:');
      console.error(`     FLUTTER_XCODE_ARCHS=${arch} npm run build:macos\n`);
    }
    throw error;
  }

  const macosDistDir = path.join(distDir, singleArch ? 'macos-local' : 'macos');
  const appSrc = path.join(mobileDir, 'build/macos/Build/Products/Release/markdown_viewer_mobile.app');
  const appDest = path.join(macosDistDir, 'markdown_viewer_mobile.app');

  copyDirectory(appSrc, appDest);

  console.log(`\n✅ macOS app built (${label}): ${appDest}`);
}

const targets = {
  ios: {
    name: 'iOS (IPA)',
    build: () => {
      console.log('\n📱 Building iOS IPA...\n');
      
      ensureFlutterConfig('ios');
      exec('flutter build ipa --export-options-plist=ios/exportOptions.plist', { cwd: mobileDir });
      
      const iosDistDir = path.join(distDir, 'ios');
      const ipaSrcDir = path.join(mobileDir, 'build/ios/ipa');
      
      fs.mkdirSync(iosDistDir, { recursive: true });
      copyFiles(ipaSrcDir, iosDistDir, /\.ipa$/);
      
      // Copy manifest and other files if present
      const entries = fs.readdirSync(ipaSrcDir);
      for (const entry of entries) {
        const srcPath = path.join(ipaSrcDir, entry);
        const destPath = path.join(iosDistDir, entry);
        if (fs.statSync(srcPath).isFile()) {
          fs.copyFileSync(srcPath, destPath);
        }
      }
      
      console.log(`\n✅ iOS IPA built: ${iosDistDir}/`);
    }
  },
  
  'ios:sim': {
    name: 'iOS Simulator',
    build: () => {
      console.log('\n📱 Building iOS Simulator app...\n');
      
      ensureFlutterConfig('ios');
      exec('flutter build ios --simulator', { cwd: mobileDir });
      
      const simDistDir = path.join(distDir, 'ios-sim');
      const appSrc = path.join(mobileDir, 'build/ios/iphonesimulator/Runner.app');
      const appDest = path.join(simDistDir, 'Runner.app');
      
      copyDirectory(appSrc, appDest);
      
      console.log(`\n✅ iOS Simulator app built: ${appDest}`);
    }
  },
  
  android: {
    name: 'Android APK (AAB with release signing)',
    build: () => {
      // Check whether release signing files are present (for status display only)
      const keystorePath = path.join(mobileDir, 'android/markdown_viewer.keystore');
      const keyPropertiesPath = path.join(mobileDir, 'android/key.properties');
      const hasKeystore = fs.existsSync(keystorePath) && fs.existsSync(keyPropertiesPath);

      if (!hasKeystore) {
        console.log('⚠️  No keystore found - still building release artifacts (unsigned)');
        console.log('   To sign release builds:');
        console.log('   1. Generate keystore: keytool -genkey -v -keystore android/markdown_viewer.keystore -keyalg RSA -keysize 2048 -validity 10000 -alias markdown_viewer');
        console.log('   2. Configure android/key.properties with your keystore password\n');
      }

      const buildModeDisplay = hasKeystore ? 'Release (signed)' : 'Release (unsigned)';

      console.log(`\n🤖 Building Android APK (${buildModeDisplay})...\n`);

      // Always build release APK
      exec('flutter build apk --release', { cwd: mobileDir });
      
      const androidDistDir = path.join(distDir, 'android');
      const apkSrcDir = path.join(mobileDir, `build/app/outputs/flutter-apk`);
      
      // Only collect release APK artifacts to avoid copying stale debug outputs.
      copyFiles(apkSrcDir, androidDistDir, /release.*\.apk$/);

      if (hasKeystore) {
        console.log(`\n🤖 Building Android App Bundle (AAB) (${buildModeDisplay})...\n`);

        exec('flutter build appbundle --release', { cwd: mobileDir });

        const aabSrcDir = path.join(mobileDir, 'build/app/outputs/bundle/release');
        copyFiles(aabSrcDir, androidDistDir, /\.aab$/);
      } else {
        console.log(`\n⏭️  Skipping Android App Bundle (AAB): no release keystore configured`);
      }

      console.log(`\n✅ Android builds complete: ${androidDistDir}/`);
      if (hasKeystore) {
        console.log(`   • APK: signed release build`);
        console.log(`   • AAB: signed release build`);
      } else {
        console.log(`   • APK: unsigned release build`);
        console.log(`   • AAB: not built`);
        console.log(`   ⚠️  Configure release signing to produce Play Store AAB`);
      }
    }
  },
  
  macos: {
    name: 'macOS App (universal)',
    build: () => buildMacos()
  },

  // Host-arch variant: the escape hatch for the lipo incompatibility above, and
  // what local iteration should use (it is also noticeably faster).
  'macos:local': {
    name: 'macOS App (host architecture)',
    build: () => buildMacos({ singleArch: true })
  }
};

/**
 * Main
 */
function main() {
  const args = process.argv.slice(2);
  
  if (args.length === 0 || args.includes('--help') || args.includes('-h')) {
    console.log(`
Flutter App Build Script

Usage:
  node mobile/build-app.js <target> [target2] ...

Targets:
  ios            Build iOS IPA for distribution
  ios:sim        Build iOS app for simulator
  android        Build Android release APK (build AAB only when release signing is configured)
  macos          Build macOS app (universal)
  macos:local    Build macOS app for this machine's architecture only
  all            Build every distribution target

Examples:
  node mobile/build-app.js android
  node mobile/build-app.js macos:local
  node mobile/build-app.js ios macos
  node mobile/build-app.js all
`);
    process.exit(0);
  }
  
  // Determine which targets to build
  let targetsToBuild = args;
  if (args.includes('all')) {
    // Variants (`ios:sim`, `macos:local`) are deliberately not part of `all`.
    targetsToBuild = Object.keys(targets).filter((key) => !key.includes(':'));
  }
  
  // Validate targets
  for (const target of targetsToBuild) {
    if (!targets[target]) {
      console.error(`❌ Unknown target: ${target}`);
      console.error(`   Available targets: ${Object.keys(targets).join(', ')}, all`);
      process.exit(1);
    }
  }
  
  console.log('🚀 Flutter App Build');
  console.log(`   Targets: ${targetsToBuild.map(t => targets[t].name).join(', ')}`);
  
  // Ensure dist directory exists
  fs.mkdirSync(distDir, { recursive: true });
  
  // Build each target
  const results = [];
  for (const target of targetsToBuild) {
    try {
      targets[target].build();
      results.push({ target, success: true });
    } catch (error) {
      console.error(`\n❌ Failed to build ${targets[target].name}:`, error.message);
      results.push({ target, success: false, error: error.message });
    }
  }
  
  // Summary
  console.log('\n' + '='.repeat(50));
  console.log('Build Summary:');
  for (const { target, success, error } of results) {
    const icon = success ? '✅' : '❌';
    const status = success ? 'Success' : `Failed: ${error}`;
    console.log(`  ${icon} ${targets[target].name}: ${status}`);
  }
  
  const failed = results.filter(r => !r.success);
  if (failed.length > 0) {
    process.exit(1);
  }
}

main();
